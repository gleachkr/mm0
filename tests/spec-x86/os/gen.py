def gen_cases() -> str:
    out = [
        "/* GENERATED by gen.py from manifest.py -- do not edit. */",
        "/* One row per exit test: the syscall's RDI, and the exit code the parent",
        "   must observe (RDI & 0xff). #include'd inside an array initializer. */",
    ]
    for t in manifest.TESTS:
        out.append(f'{{ "{t.name}", {t.rdi:#x}ULL, {t.code} }},')
    out.append("")
    return "\n".join(out)


def gen_fault_cases() -> str:
    out = [
        "/* GENERATED by gen.py from manifest.py -- do not edit. */",
        "/* One row per fault-exit test: the faulting instruction's raw bytes (the",
        "   same bytes the model decodes) and the exit code the parent must observe",
        "   (128 + signo, the shell's $? for a signal death). The harness copies the",
        "   bytes to an executable page and jumps to them. #include'd inside an array",
        "   initializer. */",
    ]
    for t in manifest.FAULT_TESTS:
        code = ", ".join(f"{b:#04x}" for b in t.instr)
        out.append(f'{{ "{t.name}", {{ {code} }}, {len(t.instr)}, {t.code} }},')
    out.append("")
    return "\n".join(out)


