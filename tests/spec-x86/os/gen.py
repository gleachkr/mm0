def mm0_nat(n: int) -> str:
    """A nat literal as a `:x` chain of hex digits with no leading zeros, the way
    a `,0x...` splice elaborates it: `x0`, `x1`, `xf :x xf`, `x1 :x x0 :x x0`."""
    assert n >= 0
    return " :x ".join("x" + d for d in format(n, "x"))


def mm0_str(data: bytes) -> str:
    """A string literal as the `ch _ _ ': … ': s1 (ch _ _)` term a `,"…"` splice
    elaborates to -- each byte `ch x<hi> x<lo>`, joined by string cons `':`."""
    def ch(b: int) -> str:
        return f"ch x{b >> 4:x} x{b & 0xf:x}"
    if not data:
        return "s0"
    chs = [ch(b) for b in data]
    if len(chs) == 1:
        return f"s1 ({chs[0]})"
    return " ': ".join(chs[:-1]) + f" ': s1 ({chs[-1]})"


def wrap_doc(doc: str) -> str:
    # One `--|` block; keep it simple, one line is fine for these.
    import textwrap
    lines = textwrap.wrap(doc, 74)
    return "\n".join("--| " + l for l in lines)


def gen_mm0() -> str:
    out = [
        "-- GENERATED by gen.py from manifest.py -- do not edit.",
        "--",
        "-- The OS-layer spec test suite's contract. One theorem *statement* per",
        "-- test, proved in os_tests.mm1 and checked against this file by mm0-c.",
        "-- The suite is the formal half of tests/spec-x86/os-audit/: each theorem",
        "-- is a positive fact a real syscall confirms.",
        "--",
        "-- Declaration order is manifest order, and os_tests.mm1 must follow it.",
        "",
        'import "../spec_lib.mm0";',
        "",
    ]
    for t in manifest.TESTS:
        out.append(wrap_doc(t.doc))
        out.append(f"theorem {t.name} (k: nat)")
        out.append("  (hk:   $ k e. Config $)")
        out.append("  (hex:  $ readException k = suc exSysCall $)")
        out.append(f"  (hrax: $ readReg k RAX = {mm0_nat(0x3c)} $)")      # sys_exit
        out.append(f"  (hrdi: $ readReg k RDI = {mm0_nat(t.rdi)} $):")
        out.append(f"  $ execExit k ({mm0_nat(t.code)}) $;")
        out.append("")
    for t in manifest.FAULT_TESTS:
        out.append(wrap_doc(t.doc))
        if t.fault_addr is None:
            out.append(f"theorem {t.name} {{k2: nat}} (k: nat)")
            out.append("  (hk:   $ k e. Config $)")
            out.append("  (hexc: $ readException k = 0 $)")           # normal running state
            out.append(f"  (hc:   $ readMemX k (readRIP k) ({mm0_str(t.instr)}) $):")  # faulting instr at RIP
        else:
            # A memory-write fault: the store target `fault_addr` is a non-writable
            # page, stated as `getMemory k @ addr = prot, b2 /\ ~(PROT_WRITE C_ prot)`.
            out.append(f"theorem {t.name} {{k2: nat}} (k prot b2: nat)")
            out.append("  (hk:   $ k e. Config $)")
            out.append("  (hexc: $ readException k = 0 $)")           # normal running state
            out.append(f"  (hc:   $ readMemX k (readRIP k) ({mm0_str(t.instr)}) $)")  # faulting instr at RIP
            # parenthesize the address: `@` binds tighter than the `:x` hex chain.
            out.append(f"  (hpage: $ getMemory k @ ({mm0_nat(t.fault_addr)}) = prot, b2 $)")  # target page
            out.append("  (hnw:  $ ~(PROT_WRITE C_ prot) $):")        # not writable -> #GP
        out.append(f"  $ E. k2 (step k k2 /\\ execExit k2 ({mm0_nat(t.code)})) $;")
        out.append("")
    for t in manifest.MMAP_TESTS:
        out.append(wrap_doc(t.doc))
        out.append(f"theorem {t.name} {{k2 m2: nat}} (i o k m: nat)")
        out.append("  (hi:    $ i e. List u8 $) (ho: $ o e. List u8 $)")
        out.append("  (hk:    $ k e. Config $)")
        out.append("  (hm:    $ m e. PageMapping (getMemory k) $)")
        out.append("  (hex:   $ readException k = suc exSysCall $)")
        out.append(f"  (hrax:  $ readReg k RAX = {mm0_nat(9)} $)")         # sys_mmap
        out.append(f"  (hrdi:  $ readReg k RDI = {mm0_nat(0)} $)")
        out.append(f"  (hflags: $ readReg k 10 = {mm0_nat(t.flags)} $)")   # MAP_PRIVATE[|MAP_ANONYMOUS]
        out.append(f"  (hfd:   $ readReg k 8 = {mm0_nat(t.fd % (1 << 64))} $)")  # fd (read as 32 bits)
        out.append(f"  (hrdx:  $ readReg k RDX = {mm0_nat(t.prot)} $)")    # PROT_READ
        out.append(f"  (hoff:  $ readReg k 9 = {mm0_nat(0)} $):")
        out.append("  $ E. k2 E. m2 (execIO (mkKS i o k m) (mkKS i o k2 m2) /\\")
        out.append(f"      readReg k2 RAX = {mm0_nat(t.ret)}) $;")
        out.append("")
    for t in manifest.MMAP_OK_TESTS:
        out.append(wrap_doc(t.doc))
        out.append(f"theorem {t.name} {{k2 m2 k3 pad buf j: nat}} (i o k m k2m mv rv kw: nat)")
        out.append("  (hi:    $ i e. List u8 $) (ho: $ o e. List u8 $)")
