#!/usr/bin/env python3
"""Generate os_tests.mm0 (the contract) and gen/cases.inc (the runtime table)
from manifest.py.

    ./gen.py            rewrite the generated files
    ./gen.py --check    fail (with a diff) if a committed file is stale

The .mm0 carries one theorem *statement* per test; the proofs live in the
hand-written os_tests.mm1, and `mm0-c` ties the two together, so this generator
never has to be trusted -- a wrong statement stops the proof discharging it.

gen/cases.inc is the same rows as a C table for the harness. The harness applies
expectations, it never recomputes them, so `code = rdi & 0xff` is done here.

Literals are `:x` chains of hex digits with no leading zeros, matching how
peano_hex's `,0x...` splices elaborate in the .mm1 -- the terms must be
identical, not merely equal.
"""

