        out.append(f"  (hflags: $ readReg k 10 = {mm0_nat(t.flags)} $)")   # MAP_PRIVATE|MAP_ANONYMOUS
        out.append(f"  (hprot: $ readReg k RDX = {mm0_nat(t.prot)} $)")    # PROT_READ|PROT_WRITE
        out.append(f"  (hfd:   $ readReg k 8 = {mm0_nat(t.fd % (1 << 64))} $)")  # anon fd = -1
        out.append(f"  (hoff:  $ readReg k 9 = {mm0_nat(0)} $)")
        out.append("  (hu64:  $ rv e. u64 $)")
